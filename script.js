/* =========================
   一覧画面から戻る
========================= */

function goBackFromList() {
  clearMenuOpeningTimer();

  if (listBackDestination === "drink") {
    showDrinkCategories();
    return;
  }

  showMainMenu();
}


/* =========================
   アニメーションタイマー解除
========================= */

function clearMenuOpeningTimer() {
  if (menuOpeningTimer !== null) {
    clearTimeout(menuOpeningTimer);
    menuOpeningTimer = null;
  }
}


